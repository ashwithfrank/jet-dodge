import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "standalone");

mkdirSync(join(outDir, "assets"), { recursive: true });

const result = spawnSync(
  join(root, "node_modules/.bin/rolldown"),
  [
    "src/game/standalone.ts",
    "--file",
    join(outDir, "script.js"),
    "--format",
    "iife",
    "--platform",
    "browser",
    "--minify",
    "--name",
    "JetDodge",
  ],
  { cwd: root, stdio: "inherit" },
);

if (result.status !== 0) {
  process.exit(result.status ?? 1);
}

const tokens = readFileSync(join(root, "src/styles.css"), "utf8");
const gameCss = readFileSync(join(root, "src/game/styles.css"), "utf8");
const tokenStart = tokens.indexOf(":root");
const tokenEnd = tokens.indexOf("@layer");
const tokenBlock = tokens.slice(tokenStart, tokenEnd);
writeFileSync(
  join(outDir, "style.css"),
  `*, *::before, *::after { box-sizing: border-box; }
html, body, #game { margin: 0; height: 100%; background: #05070c; color: #e8eef8; overflow: hidden; }
button:not(:disabled), [role="button"]:not(:disabled) { cursor: pointer; }
${tokenBlock}
${gameCss}
`,
);

try {
  copyFileSync(join(root, "public/favicon.svg"), join(outDir, "assets/favicon.svg"));
} catch {
  /* favicon generated by brand pass */
}

console.log("standalone build written to", outDir);
